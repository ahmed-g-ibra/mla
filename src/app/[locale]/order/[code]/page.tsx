import Image from 'next/image';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import type { Metadata } from 'next';
import { productBySlug } from '@/data/products';
import { formatMoney } from '@/lib/currency';
import { getDictionary, isLocale } from '@/lib/i18n';
import { IMAGE_BLUR } from '@/lib/image';
import { decodeOrder } from '@/lib/order-code';
import { SITE_URL } from '@/lib/seo';
import { whatsappLink } from '@/lib/store-config';
import { GLYPHS, Glyph } from '@/components/Glyph';
import { WhatsAppIcon } from '@/components/Icons';
import { SectionHeading } from '@/components/SectionHeading';

/**
 * A shareable order.
 *
 * The one dynamic route on the site: the order travels in the path, so there
 * is nothing to prerender. Deliberately noindex — these links are private to
 * whoever holds them.
 */
export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string; code: string }>;
}): Promise<Metadata> {
  const { locale, code } = await params;
  const loc = isLocale(locale) ? locale : 'en';
  const dict = getDictionary(loc);
  const order = decodeOrder(code, loc);
  if (!order) return { title: dict.order.notFound, robots: { index: false } };

  const count = order.lines.reduce((n, l) => n + l.qty, 0);
  const title = `${dict.order.sharedTitle} ${order.reference}`;
  const description = `${count} ${
    count === 1 ? dict.order.piece : dict.order.pieces
  } — ${formatMoney(order.totalUsd, order.currency, loc)}`;

  return {
    title,
    description,
    robots: { index: false, follow: false },
    // The card itself is generated by opengraph-image.tsx alongside this file.
    openGraph: {
      type: 'website',
      siteName: 'MLA',
      title,
      description,
      url: `${SITE_URL}/${loc}/order/${code}`,
      locale: loc === 'ar' ? 'ar_AR' : 'en_US',
    },
  };
}

export default async function SharedOrderPage({
  params,
}: {
  params: Promise<{ locale: string; code: string }>;
}) {
  const { locale, code } = await params;
  if (!isLocale(locale)) notFound();
  const dict = getDictionary(locale);
  const order = decodeOrder(code, locale);

  if (!order) {
    return (
      <div className="mx-auto max-w-xl px-4 py-24 text-center">
        <Glyph char={GLYPHS.wedjat} className="text-4xl text-papyrus-400" />
        <h1 className="mt-4 text-2xl font-semibold text-ink-900">
          {dict.order.notFound}
        </h1>
        <p className="mt-2 text-ink-500">{dict.order.notFoundHint}</p>
        <Link
          href={`/${locale}/collections`}
          className="mt-6 inline-flex min-h-12 cursor-pointer items-center rounded-sm bg-lapis-800 px-6 font-semibold text-papyrus-50 transition-colors duration-200 hover:bg-lapis-900"
        >
          {dict.order.backToShop}
        </Link>
      </div>
    );
  }

  const money = (usd: number) => formatMoney(usd, order.currency, locale);
  const count = order.lines.reduce((n, l) => n + l.qty, 0);

  const message = [
    dict.cart.whatsappIntro,
    `${dict.order.reference}: ${order.reference}`,
    '',
    `${SITE_URL}/${locale}/order/${code}`,
  ].join('\n');

  return (
    <div className="mx-auto max-w-4xl px-4 py-12 sm:px-6 lg:px-8">
      <SectionHeading
        glyph={GLYPHS.ankh}
        title={`${dict.order.sharedTitle} ${order.reference}`}
        body={dict.order.sharedLead}
        align="start"
        as="h1"
      />

      <p className="mt-4 text-sm text-ink-500">
        {count} {count === 1 ? dict.order.piece : dict.order.pieces}
      </p>

      <ul className="mt-8 divide-y divide-papyrus-300 border-y border-papyrus-300">
        {order.lines.map((line) => {
          const product = productBySlug(line.slug)!;
          return (
            <li key={line.slug} className="flex gap-4 py-5">
              <Link
                href={`/${locale}/products/${line.slug}`}
                className="relative h-24 w-24 shrink-0 cursor-pointer overflow-hidden rounded-sm border border-papyrus-300 bg-white"
              >
                <Image
                  src={product.images[0]}
                  alt=""
                  fill
                  sizes="96px"
                  className="object-contain p-1.5"
                  placeholder="blur"
                  blurDataURL={IMAGE_BLUR}
                />
              </Link>
              <div className="min-w-0 flex-1">
                <Link
                  href={`/${locale}/products/${line.slug}`}
                  className="cursor-pointer font-semibold text-ink-900 transition-colors duration-200 hover:text-lapis-700"
                >
                  {line.name}
                </Link>
                <p className="mt-0.5 text-sm text-ink-500">
                  {product.material[locale]} ·{' '}
                  <bdi>{product.heightCm} cm</bdi>
                </p>
                <p className="mt-1 text-sm text-ink-500 tabular-nums">
                  {money(product.priceUsd)} × {line.qty}
                </p>
              </div>
              <p className="shrink-0 font-semibold tabular-nums text-ink-900">
                {money(line.totalUsd)}
              </p>
            </li>
          );
        })}
      </ul>

      <dl className="mt-6 ms-auto max-w-xs space-y-2 text-sm">
        <div className="flex justify-between gap-4">
          <dt className="text-ink-500">{dict.cart.shipping}</dt>
          <dd className="font-medium text-malachite-700">
            {dict.cart.shippingFree}
          </dd>
        </div>
        <div className="flex justify-between gap-4 border-t border-papyrus-300 pt-2 text-base">
          <dt className="font-semibold">{dict.cart.total}</dt>
          <dd className="font-semibold tabular-nums">{money(order.totalUsd)}</dd>
        </div>
        <div className="flex justify-between gap-4 text-xs text-ink-500">
          <dt>{dict.vat.ofWhich}</dt>
          <dd className="tabular-nums">{money(order.vatUsd)}</dd>
        </div>
      </dl>

      <div className="mt-10 flex flex-wrap gap-3">
        <a
          href={whatsappLink(message)}
          target="_blank"
          rel="noopener noreferrer"
          className="inline-flex min-h-12 cursor-pointer items-center gap-2.5 rounded-sm bg-malachite-600 px-6 font-semibold text-papyrus-50 transition-colors duration-200 hover:bg-malachite-700"
        >
          <WhatsAppIcon />
          {dict.shipping.contactCta}
        </a>
        <Link
          href={`/${locale}/collections`}
          className="inline-flex min-h-12 cursor-pointer items-center rounded-sm border border-lapis-700 px-6 font-semibold text-lapis-800 transition-colors duration-200 hover:bg-lapis-800 hover:text-papyrus-50"
        >
          {dict.order.backToShop}
        </Link>
      </div>
    </div>
  );
}
